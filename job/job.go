func GetSparrowdoConfig (p string, filename string) interface{} {

	path := filepath.Join(utils.SparkyProjectDir(p),filename)

    dat, err := os.ReadFile(path)

	if err != nil {
		log.Fatalf("GetSparrowdoConfig: Error reading file:", err)
	}

	var c interface{}

	err = json.Unmarshal(dat, &c)

	if err != nil {
		log.Fatalf("GetSparrowdoConfig: error unmarshaling JSON: %v", err)
	}

	return c
}
